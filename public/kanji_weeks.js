// 現在の週番号を基準日から計算（1〜48、4クォーター×12週）
function getCurrentWeek(){
  const BASE = new Date('2026-04-06T00:00:00+09:00');
  const now = new Date();
  const diffDays = Math.floor((now - BASE) / (1000*60*60*24));
  const week = Math.floor(diffDays / 7) + 1;
  return Math.min(Math.max(1, week), 48);
}

// 指定owner・週の漢字データを取得
// 手動データがあればそれ、なければプールから週ごとに25字を自動選出
function getWeekKanji(owner, week){
  const data = KANJI_WEEKS[owner] || KANJI_WEEKS.kanka;
  if(data[week]) return data[week];
  const pool = (owner === 'hanano') ? (typeof KANJI_POOL_HANANO !== 'undefined' ? KANJI_POOL_HANANO : null)
                                    : (typeof KANJI_POOL_KANKA !== 'undefined' ? KANJI_POOL_KANKA : null);
  if(pool && pool.length >= 25){
    const arr = pool.slice();
    let seed = week * 9301 + 49297;
    function rnd(){ seed = (seed * 9301 + 49297) % 233280; return seed / 233280; }
    for(let i = arr.length - 1; i > 0; i--){
      const j = Math.floor(rnd() * (i + 1));
      const t = arr[i]; arr[i] = arr[j]; arr[j] = t;
    }
    return arr.slice(0, 25);
  }
  return data[1];
}

// 読みクイズ・書きクイズ用：今週の漢字を {k:漢字, y:よみ} 形式で返す
function getWeekKanjiList(owner, week){
  const data = getWeekKanji(owner, week);
  return data.map(function(item){
    // bは送り仮名なしのよみ、ansが漢字。よみは送り仮名を除いた形
    return { k: item.ans, y: item.b };
  });
}
